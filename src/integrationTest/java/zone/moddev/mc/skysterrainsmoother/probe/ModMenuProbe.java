package zone.moddev.mc.skysterrainsmoother.probe;

import java.io.IOException;
import java.lang.reflect.Field;
import java.util.List;
import net.minecraft.client.Minecraft;
import net.minecraft.client.gui.GuiButton;
import net.minecraft.client.gui.GuiScreen;
import net.minecraft.client.resources.I18n;
import net.minecraftforge.fml.client.GuiModList;
import net.minecraftforge.fml.client.config.GuiConfig;
import net.minecraftforge.fml.client.config.GuiConfigEntries;
import net.minecraftforge.fml.common.Loader;
import net.minecraftforge.fml.common.ModContainer;

/** Exercises the actual Mods list; a working factory alone does not make its Config button visible. */
final class ModMenuProbe {
    static void run(Minecraft minecraft) {
        GuiScreen parent = minecraft.currentScreen;
        int tooltips = 0;

        for (String modId : new String[] { "skysgrassslabs", "skysterrainsmoother" }) {
            ModContainer mod = Loader.instance().getIndexedModList().get(modId);
            RuntimeProbe.require(!mod.getMetadata().autogenerated, "metadata must load for " + modId);
            RuntimeProbe.require(modId.equals(mod.getMetadata().modId)
                    && !mod.getMetadata().description.trim().isEmpty()
                    && !mod.getMetadata().authorList.isEmpty(), "the Mods page has real information for " + modId);

            ModListScreen mods = new ModListScreen(parent);
            minecraft.displayGuiScreen(mods);
            mods.select(modId);
            draw(minecraft, mods);
            screenshot(minecraft, modId + "-mod-info.png");
            mods.openConfig();
            RuntimeProbe.require(minecraft.currentScreen instanceof GuiConfig,
                    "the actual Config button opens the settings for " + modId);
            GuiConfig config = (GuiConfig) minecraft.currentScreen;

            for (int index = 0; index < config.configElements.size(); index++) {
                String key = config.configElements.get(index).getLanguageKey() + ".tooltip";
                String translated = I18n.format(key);
                RuntimeProbe.require(!translated.equals(key) && !translated.trim().isEmpty(),
                        "translated tooltip exists for " + key);
                RuntimeProbe.require(config.configElements.get(index).getComment() != null
                        && !config.configElements.get(index).getComment().trim().isEmpty(),
                        "plain help text remains available for " + key);

                @SuppressWarnings("unchecked")
                List<String> tooltip = (List<String>) field(GuiConfigEntries.ListEntryBase.class,
                        config.entryList.listEntries.get(index), "toolTip");
                String text = String.join("\n", tooltip);
                RuntimeProbe.require(text.contains(translated) && !text.contains("No tooltip defined."),
                        "Forge builds the real entry tooltip for " + key);
                draw(minecraft, config);
                config.drawToolTip(tooltip, 20, 70);
                screenshot(minecraft, modId + "-" + config.configElements.get(index).getName() + "-tooltip.png");
                tooltips++;
            }

            minecraft.displayGuiScreen(parent);
        }

        RuntimeProbe.require(tooltips == 5, "all five settings have usable tooltips");
        System.out.println("SKY_MOD_MENU_PASS metadata=2 config_buttons=2 tooltips=" + tooltips);
    }

    private static void draw(Minecraft minecraft, GuiScreen screen) {
        minecraft.getFramebuffer().bindFramebuffer(true);
        minecraft.entityRenderer.setupOverlayRendering();
        screen.drawScreen(0, 0, 0);
    }

    private static void screenshot(Minecraft minecraft, String filename) {
        net.minecraft.util.ScreenShotHelper.saveScreenshot(minecraft.gameDir, filename,
                minecraft.displayWidth, minecraft.displayHeight, minecraft.getFramebuffer());
        RuntimeProbe.require(new java.io.File(minecraft.gameDir, "screenshots/" + filename).isFile(),
                "saved screen capture " + filename);
    }

    private static Object field(Class<?> owner, Object instance, String name) {
        try {
            Field field = owner.getDeclaredField(name);
            field.setAccessible(true);
            return field.get(instance);
        } catch (ReflectiveOperationException failure) {
            throw new IllegalStateException("Cannot inspect Forge's menu field " + name, failure);
        }
    }

    private static final class ModListScreen extends GuiModList {
        ModListScreen(GuiScreen parent) {
            super(parent);
        }

        void select(String modId) {
            List<?> mods = (List<?>) field(GuiModList.class, this, "mods");
            for (int index = 0; index < mods.size(); index++) {
                if (((ModContainer) mods.get(index)).getModId().equals(modId)) {
                    selectModIndex(index);
                    return;
                }
            }
            throw new AssertionError("The Mods list is missing " + modId);
        }

        void openConfig() {
            GuiButton button = (GuiButton) field(GuiModList.class, this, "configModButton");
            RuntimeProbe.require(button.visible && button.enabled, "the Config button is visible and enabled");
            try {
                super.actionPerformed(button);
            } catch (IOException failure) {
                throw new IllegalStateException("The Config button failed", failure);
            }
        }
    }

    private ModMenuProbe() {
    }
}

